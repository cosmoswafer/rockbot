// ─── Live Integration Probe: DeepSeek vision (image input) contract ─────────
//
// DFD covered: _dfd/ai/ai-provider.md §2c, _dfd/interception/image-interception.md
// Issue: ReLab/Ideas #116 — "[BUG] DeepSeek provider still doesn't support vision
// (should)". Collects live API data that drove the diagnosis:
//   * deepseek-v4-flash-vision-exp accepts OpenAI-style `image_url` content parts
//     (exactly what rockbot serializes via ChatMessage::user_with_images).
//   * Non-vision models (deepseek-v4-pro) reject image parts with HTTP 400 —
//     so DeepSeekProvider must keep stripping images for those models.
//   * Images in system/assistant messages are rejected (400) — a forwarded-body
//     fix must only ever place ImageUrl parts in user messages.
//   * The literal text "[image]" is NOT the reserved placeholder token (HTTP 200),
//     so memory summaries containing "[image]" remain safe for vision models.
//   * Per-image prompt-token cost stays under DeepSeek's 384-token cap.
//
// Ignored by default — requires the workspace `config.toml` (does NOT require the
// bot to be running). Run with:
//
//   cargo test -p rockbot --test deepseek_vision_real -- --ignored --nocapture
//
// NOTE: these are pure API-contract probes against api.deepseek.com; they assert
// nothing about provider internals, so they remain valid both before and after the
// fix that removes DeepSeekProvider's unconditional image stripping.

